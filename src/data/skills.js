/** Calculate progress percentage for a specific skill */
export function getSkillProgress(skillInput, progress = {}) {
  const skill = typeof skillInput === "string" ? skills.find((s) => s.id === skillInput) : skillInput;
  if (!skill) return 0;
  const completedLessons = progress.completedLessons || [];
  if (!skill.relatedLessons || skill.relatedLessons.length === 0) {
    const raw = progress.skillProgress?.[skill.id] || 0;
    return Math.min(100, raw);
  }
  const completedCount = skill.relatedLessons.filter((id) => completedLessons.includes(id)).length;
  return Math.min(100, Math.round((completedCount / skill.relatedLessons.length) * 100));
}

/** Check if skill is unlocked */
export function isSkillUnlocked(skillInput, progress = {}) {
  const skill = typeof skillInput === "string" ? skills.find((s) => s.id === skillInput) : skillInput;
  if (!skill) return false;
  const xp = progress.xp || 0;
  const skillPercent = getSkillProgress(skill, progress);
  return skillPercent > 0 || xp >= (skill.xpRequired || 0);
}

/** Get all skills enriched with live progress */
export function getAllSkillsWithProgress(progress = {}) {
  return skills.map((skill) => {
    const percent = getSkillProgress(skill, progress);
    const unlocked = isSkillUnlocked(skill, progress);
    const isCompleted = percent >= 100;
    const isCurrent = !isCompleted && percent > 0;
    return {
      ...skill,
      progress: percent,
      unlocked,
      isUnlocked: unlocked,
      status: isCompleted ? "completed" : isCurrent ? "current" : unlocked ? "unlocked" : "locked",
    };
  });
}